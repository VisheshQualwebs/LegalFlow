// Conditional Operator
// Give Grade according to percentage

let marks = 100;
if (marks > 90) {
    console.log('A');
} else if (marks <= 90 && marks > 80) {
    console.log('B');
} else if (marks <= 80 && marks > 70) {
    console.log('C');
} else if (marks <= 70 && marks > 33) {
    console.log('D');
} else {
    console.log('F');
}
