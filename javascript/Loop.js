// Print tables

console.log('Using For Loop')
let n = 10;
for(let i=1; i<=n; i++){
    console.log(n  + ' x ' + i + ' = ' + n*i);
}

console.log('Using while loop')
let i = 1;
while(i <= 10){
    console.log(n  + ' x ' + i + ' = ' + n*i);
    i++;
}

console.log('Using Do While loop')
i = 1;
do{
    console.log(n  + ' x ' + i + ' = ' + n*i);
    i++;
}while(i <= 10)